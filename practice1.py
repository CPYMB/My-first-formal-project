#若输入违规信息，需要有提示，如输入0，字符串
#输出部分：需要输出用户输入数字次数，以及输入数字的和与平均数
#中间部分：需要一个计数盒，记录用户输入次数，实现每次输入都自增1
#需要一个输入总和盒，累加用户输入的数字，得出总和
#利用总和盒的数据与次数盒运算得到总和平均数
#利用循环判断为真实现用户能重复输入，利用判断条件判断结束循环输出结果
#特殊情况单独写出，可能会增加空间复杂度？
# ========== 第 2 步：Python 代码 ==========
total = 0
count = 0
while True:
    inf = input("请随机输入任意数字:")
    try:
        number = int(inf)
    except ValueError:
        print("请不要输入除数字外的字符")
        continue
    if number != 0:
        total += number
        count += 1
    elif number == 0 and count == 0:
        print("请不要第一次输入0,您总共输入1次,输入总和为0,平均数为0")
        break
    elif number == 0 and count != 0:
        print(f"游戏结束，您总共输入了{count}次，输入总和为{total},平均数为{total/count}")
        break







