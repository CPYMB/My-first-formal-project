for num in range(3, 201, 2):                 # 只遍历奇数，省一半运算
    is_prime = True                          # 先假设它是质数
    for d in range(2, int(num ** 0.5) + 1):  # 只试到 √num
        if num % d == 0:                     # 能被整除
            is_prime = False                 # 就不是质数
            break                            # 不用再试
    if is_prime:
        print(num, end=" ")
